const dictionaries: Record<Locale, Dictionary> = { en, ar }

export const LOCALE_META: Record<Locale, { label: string; dir: 'ltr' | 'rtl' }> = {
  en: { label: 'English', dir: 'ltr' },
  ar: { label: 'العربية', dir: 'rtl' },
}

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string

export function createTranslator(locale: Locale): Translate {
  const dict = dictionaries[locale]
  const numberFormat = new Intl.NumberFormat(locale)
  return (key, vars) => {
    let text = dict[key] ?? en[key]
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        const formatted = typeof value === 'number' ? numberFormat.format(value) : value
        text = text.replaceAll(`{${name}}`, formatted)
      }
    }
    return text
  }
}

export function formatDate(iso: string, locale: Locale) {
  return new Intl.DateTimeFormat(locale, { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' }).format(
    new Date(`${iso}T00:00:00Z`),
  )
}
